# mqtt_bridge/led.py
"""On-board status LED for the aircraft bridge (stdlib only).

At the bench there is no screen on the aircraft computer, so one LED shows
what the bridge sees. On the XBLink that is the small green "SYS" LED, which
Linux calls /sys/class/leds/ACT (normally it flickers on storage activity).

    Slow even blink (1 s on, 1 s off)   all good: Cube data in, broker connected
    Double flash, pause                 no data from the Cube (wiring, baud, Cube)
    Fast flicker                        Cube data in, broker NOT connected (LTE)
    Stuck on or stuck off               bridge frozen
    Normal storage flicker              bridge not running (systemd restores it)

"No Cube data" wins over "no broker": at the bench the Cube is the thing to
fix first, and with no Cube data there is nothing to send anyway.

Every pattern is generated by this thread, never by a kernel blink trigger, so
if the bridge process freezes the LED freezes too instead of looking healthy.

Never allowed to affect the link: the first failed write is logged and the LED
is left alone from then on.
"""

import logging
import time
from pathlib import Path

logger = logging.getLogger(__name__)

OK = "ok"
NO_CUBE = "no_cube"
NO_BROKER = "no_broker"

# Each pattern is a list of (led_on, seconds) steps, all 2 s long, so the state
# is re-checked every 2 s.
PATTERNS = {
    OK: [(True, 1.0), (False, 1.0)],
    NO_CUBE: [(True, 0.15), (False, 0.15), (True, 0.15), (False, 1.55)],
    NO_BROKER: [(True, 0.1), (False, 0.1)] * 10,
}

DESCRIPTIONS = {
    OK: "slow blink (Cube data in, broker connected)",
    NO_CUBE: "double flash (no data from the Cube)",
    NO_BROKER: "fast flicker (broker not connected)",
}

# Cube data counts as "arriving" if a frame came in within this many seconds.
# The Cube sends HEARTBEAT at 1 Hz and much else faster, so 3 s is generous.
CUBE_QUIET_S = 3.0


def choose_state(cube_ok, broker_ok):
    """Which pattern to show. Pure."""
    if not cube_ok:
        return NO_CUBE
    if not broker_ok:
        return NO_BROKER
    return OK


class SysfsLed:
    """One Linux LED under /sys/class/leds/<name>.

    take() switches off the kernel trigger (remembering it), set() turns the LED
    on or off, restore() puts the original trigger back. After the first error
    every call is a no-op returning False.
    """

    def __init__(self, path):
        self.path = Path(path)
        self.ok = True
        self._original_trigger = None

    def _fail(self, what, exc):
        if self.ok:
            logger.error("status LED %s: %s failed (%s); LED disabled, the link "
                         "is unaffected", self.path, what, exc)
        self.ok = False
        return False

    def take(self):
        try:
            text = (self.path / "trigger").read_text()
            # The active trigger is the one in [brackets].
            start, end = text.find("["), text.find("]")
            if start != -1 and end > start:
                self._original_trigger = text[start + 1:end]
            (self.path / "trigger").write_text("none")
            return True
        except OSError as exc:
            return self._fail("take", exc)

    def set(self, on):
        if not self.ok:
            return False
        try:
            (self.path / "brightness").write_text("1" if on else "0")
            return True
        except OSError as exc:
            return self._fail("set", exc)

    def restore(self):
        if self._original_trigger is None:
            return
        try:
            (self.path / "trigger").write_text(self._original_trigger)
        except OSError as exc:
            logger.warning("status LED %s: could not restore trigger %r (%s)",
                           self.path, self._original_trigger, exc)


class CubeActivity:
    """Turns a growing frame counter into "is Cube data arriving?"."""

    def __init__(self, quiet_s=CUBE_QUIET_S):
        self.quiet_s = quiet_s
        self._last_count = None
        self._last_change = None

    def update(self, count, now):
        if self._last_count is None:
            self._last_count = count        # first look: nothing seen yet
        elif count != self._last_count:
            self._last_count = count
            self._last_change = now
        return self._last_change is not None and now - self._last_change < self.quiet_s


def run_status_led(led, stop, frame_count, broker_up, patterns=PATTERNS,
                   clock=time.monotonic):
    """Drive `led` until `stop` (a threading.Event) is set.

    frame_count() returns the total frames received from the Cube so far,
    broker_up() whether MQTT is connected.
    """
    if not led.take():
        return
    logger.info("status LED on %s", led.path)
    activity = CubeActivity()
    shown = None
    try:
        while not stop.is_set():
            try:
                cube_ok = activity.update(frame_count(), clock())
                state = choose_state(cube_ok, bool(broker_up()))
            except Exception:
                logger.exception("status LED: could not read bridge state")
                state = NO_CUBE
            if state != shown:
                shown = state
                logger.info("status LED: %s", DESCRIPTIONS[state])
            for on, seconds in patterns[state]:
                if not led.set(on):
                    return
                if stop.wait(seconds):
                    return
    finally:
        led.restore()
